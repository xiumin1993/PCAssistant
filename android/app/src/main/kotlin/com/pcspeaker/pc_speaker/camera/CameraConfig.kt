package com.pcspeaker.pc_speaker.camera

/**
 * CameraConfig —— 采集链路的全局参数
 * ----------------------------------------------------------------------------
 * 集中放在这里，是因为"并行度""画质"这类数字在采集链路的好几个类里都要用
 * （线程池、取件柜槽位、编码器）。散落各处的话，改一个值要去好几个文件找。
 */
internal object CameraConfig {

    // ======================================================================
    // 【v3.8.2】并行度按"这台机器实际有多少核"运行时推导，不写死任何数字。
    // 本项目要跑在各种手机上：4 核的低端机、8 核主流机、16 核旗舰机都有。
    // 写死 4 或 8 都会在别的机器上出问题（低端机 UI 卡死 / 旗舰机吃不满）。
    // ======================================================================

    /** 可用核数。夹在 1..16：防止设备报错返回 0 或虚高值。 */
    val CPU_COUNT = Runtime.getRuntime().availableProcessors().coerceIn(1, 16)

    /**
     * 帧间并行度：同时最多几帧在"JPEG 编码"流水线里跑。
     * 取"核数的一半"——另一半留给 UI 线程、Dart 线程、相机采集线程和系统，
     * 否则画面是流畅了但界面会卡、取帧也会被拖慢。
     * 夹在 1..4：上限 4 是因为相机出帧本身就 ≤30fps，4 路已经足够吃满，
     * 再多只会拉长单帧延迟（延迟 = 首帧处理时间，与吞吐无关）。
     */
    val PIPELINE_WORKERS = (CPU_COUNT / 2).coerceIn(1, 4)

    // ══════════════════════════════════════════════════════════════════
    // 【v3.16】预览/编码方案的 A/B 开关（改动小 → 用配置切换，不建分支）
    // ══════════════════════════════════════════════════════════════════
    // 排查预览卡顿时，最快的办法是"把某一个变量单独拨一下，看 CamPerf 怎么变"。
    // 这几个值就是干这个用的：改完重新跑一次即可，不用碰任何业务逻辑。
    // ⚠ 默认值 = 自动推导的结果；只有排查时才临时改，验证完要改回 -1。

    /**
     * JPEG 并行度调试钩。-1 = 用上面推导出的 PIPELINE_WORKERS。
     *
     * 用来验证"是不是编码线程把 UI 线程的核抢走了"：
     * 实测（Redmi 4X，1280x720）4 路并行时单帧 jpeg 从 25ms 涨到 60ms，
     * 怀疑是核被占满后 GC/降频连带拖慢。把它调成 2 看 jpeg 与帧率怎么变，
     * 就能判断"更多并行"到底是帮忙还是添乱。
     */
    const val PIPELINE_WORKERS_OVERRIDE = -1

    /** 实际生效的并行度（派生值，流水线与缓冲池都必须用它，两边要一致） */
    val ACTIVE_WORKERS: Int
        get() = if (PIPELINE_WORKERS_OVERRIDE >= 1) {
            PIPELINE_WORKERS_OVERRIDE.coerceIn(1, 8)
        } else {
            PIPELINE_WORKERS
        }

    /**
     * Camera1 回调缓冲池在"并行度"之外【多给几块】。
     *
     * 相机手里必须常备几块空缓冲才不会等我们 —— 缓冲一断流，帧率立刻被压下去
     *（背压）。给多了纯属浪费内存（每块 = 宽×高×1.5 字节，1280x720 约 1.3MB）；
     * 给少了相机就会等。默认 3 是"并行度之外再留 3 块周转"的经验值。
     */
    const val CALLBACK_BUFFER_EXTRA = 3

    /**
     * JPEG 质量。
     *
     * 上行链路是【有损】的：每帧画面都要压成 JPEG 才发出去。
     * 为什么不发原始数据：1280x720 的 NV21 一帧就是 1.38 MB，
     * 24 fps 下 33 MB/s —— 手机端编码、WiFi、PC 端解码三边都吃不消；
     * 压成 JPEG 后一帧约 100~180 KB，只有 2.4~4.3 MB/s。
     * 代价就是清晰度：这是实时流绕不开的取舍。
     *
     * 质量值怎么定的：
     * 【v3.12】60 → 75：60 在 720p 上块效应明显（文字、网格、树叶处最扎眼）。
     * 【v3.13】75 → 90：换成 libjpeg-turbo 之后编码从 51ms 降到 24ms，
     *   而一帧的预算是 41ms（1/24 秒）—— 余量是实打实空出来的，
     *   没有理由不把它花在画质上。90 大约涨到 28ms，仍在预算内；
     *   体积 100KB → 约 180KB（4.3MB/s），局域网毫无压力。
     *   再往上（95+）收益已经很难看出来，体积却还在一路涨，停在这里。
     *
     * 带宽真吃紧时的正确做法是调低【画质档位】（界面下拉框），
     * 而不是让每一档都糊 —— 档位仍只取设备上报的最高档，代码不替设备降档。
     */
    const val JPEG_QUALITY = 90

    /**
     * 【v3.14】只有"单次对焦"（FOCUS_MODE_AUTO）模式时的重新对焦间隔。
     * 单次对焦不会跟着场景变化 —— 手机一动、物体一挪就失焦，所以必须
     * 定期重触发。4 秒是折中：太频繁画面会不停"拉风箱"（来回呼吸），
     * 太慢则移动完要糊很久。连续对焦模式下这个值用不到。
     */
    const val REFOCUS_INTERVAL_MS = 4000L

    /** 占位用的空帧：某帧处理失败时用它顶上，防止保序队列卡死 */
    val EMPTY_JPEG = ByteArray(0)
}
